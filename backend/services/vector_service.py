from pathlib import Path
from typing import Any, Dict, List

import chromadb
from sentence_transformers import SentenceTransformer

from backend.services.retrieval_service import retrieval_service


class VectorService:
    """
    Vector retrieval service for the Compliance & Retrieval Agent.

    Responsibilities:
    - Reuse chunks generated by RetrievalService.
    - Generate semantic embeddings.
    - Store embeddings in ChromaDB.
    - Perform semantic similarity search.
    """

    COLLECTION_NAME = "seaguard_maritime_knowledge"
    EMBEDDING_MODEL = "all-MiniLM-L6-v2"

    def __init__(self):

        # Project root:
        # SeaGuard-AI-Maritime-Compliance-System/
        self.project_root = (
            Path(__file__).resolve().parents[2]
        )

        # Local persistent ChromaDB storage
        self.vector_db_path = (
            self.project_root / "vector_store"
        )

        self.vector_db_path.mkdir(
            parents=True,
            exist_ok=True
        )

        # Load sentence-transformer embedding model
        self.embedding_model = SentenceTransformer(
            self.EMBEDDING_MODEL
        )

        # Persistent ChromaDB client
        self.client = chromadb.PersistentClient(
            path=str(self.vector_db_path)
        )

        # Create or load collection
        self.collection = (
            self.client.get_or_create_collection(
                name=self.COLLECTION_NAME,
                metadata={
                    "description":
                        "SeaGuard AI maritime compliance "
                        "knowledge base",
                    "hnsw:space": "cosine"
                }
            )
        )

    # -------------------------------------------------
    # RESET COLLECTION
    # -------------------------------------------------

    def _reset_collection(self) -> None:
        """
        Delete and recreate the vector collection.
        """

        try:
            self.client.delete_collection(
                name=self.COLLECTION_NAME
            )

        except Exception:
            pass

        self.collection = (
            self.client.get_or_create_collection(
                name=self.COLLECTION_NAME,
                metadata={
                    "description":
                        "SeaGuard AI maritime compliance "
                        "knowledge base",
                    "hnsw:space": "cosine"
                }
            )
        )

    # -------------------------------------------------
    # BUILD VECTOR DATABASE
    # -------------------------------------------------

    def build_vector_store(
        self,
        rebuild: bool = False
    ) -> Dict[str, Any]:
        """
        Create embeddings for maritime knowledge-base
        chunks and store them in ChromaDB.
        """

        if rebuild:
            self._reset_collection()

        existing_count = (
            self.collection.count()
        )

        # Prevent duplicate insertion
        if existing_count > 0:
            return {
                "status": "already_built",
                "total_chunks": existing_count
            }

        # RetrievalService.build_chunks() already
        # loads the knowledge-base documents internally.
        chunks = (
            retrieval_service.build_chunks()
        )

        if not chunks:
            return {
                "status": "no_documents",
                "total_chunks": 0
            }

        # Get text from every knowledge chunk
        texts = [
            chunk["content"]
            for chunk in chunks
        ]

        # Generate embeddings
        embeddings = (
            self.embedding_model.encode(
                texts,
                convert_to_numpy=True,
                normalize_embeddings=True,
                show_progress_bar=False
            )
        )

        ids = []
        metadatas = []

        for index, chunk in enumerate(
            chunks,
            start=1
        ):

            # Stable unique ID for each chunk
            chunk_id = (
                f"knowledge_chunk_{index}"
            )

            ids.append(chunk_id)

            metadatas.append({
                "filename":
                    str(chunk["filename"]),

                "source":
                    str(chunk["source"]),

                "file_type":
                    str(chunk["file_type"]),

                "chunk_id":
                    int(chunk["chunk_id"])
            })

        # Store documents + embeddings + metadata
        self.collection.add(
            ids=ids,
            documents=texts,
            embeddings=embeddings.tolist(),
            metadatas=metadatas
        )

        return {
            "status": "built",
            "total_chunks": len(chunks)
        }

    # -------------------------------------------------
    # SEMANTIC VECTOR SEARCH
    # -------------------------------------------------

    def semantic_search(
        self,
        query: str,
        limit: int = 5
    ) -> List[Dict[str, Any]]:
        """
        Search the maritime knowledge base using
        semantic vector similarity.
        """

        query = query.strip()

        if not query:
            return []

        # Supported result range
        limit = max(
            1,
            min(limit, 10)
        )

        # Automatically build the vector database
        # when it has not been initialized yet.
        if self.collection.count() == 0:

            self.build_vector_store()

        total_chunks = (
            self.collection.count()
        )

        if total_chunks == 0:
            return []

        result_limit = min(
            limit,
            total_chunks
        )

        # Convert user query into embedding vector
        query_embedding = (
            self.embedding_model.encode(
                query,
                convert_to_numpy=True,
                normalize_embeddings=True
            )
        )

        # Vector similarity search
        results = (
            self.collection.query(
                query_embeddings=[
                    query_embedding.tolist()
                ],
                n_results=result_limit,
                include=[
                    "documents",
                    "metadatas",
                    "distances"
                ]
            )
        )

        documents = (
            results.get("documents")
            or [[]]
        )[0]

        metadatas = (
            results.get("metadatas")
            or [[]]
        )[0]

        distances = (
            results.get("distances")
            or [[]]
        )[0]

        output = []

        for (
            document,
            metadata,
            distance
        ) in zip(
            documents,
            metadatas,
            distances
        ):

            if document is None:
                continue

            metadata = metadata or {}

            # Collection uses cosine distance:
            # smaller distance = more similar.
            similarity_score = max(
                0.0,
                min(
                    1.0,
                    1.0 - float(distance)
                )
            )

            output.append({
                "filename":
                    metadata.get(
                        "filename",
                        "unknown"
                    ),

                "source":
                    metadata.get(
                        "source",
                        ""
                    ),

                "file_type":
                    metadata.get(
                        "file_type",
                        ""
                    ),

                "chunk_id":
                    int(
                        metadata.get(
                            "chunk_id",
                            0
                        )
                    ),

                "similarity_score":
                    round(
                        similarity_score,
                        4
                    ),

                "content":
                    document
            })

        return output

    # -------------------------------------------------
    # VECTOR STORE INFORMATION
    # -------------------------------------------------

    def get_vector_store_info(
        self
    ) -> Dict[str, Any]:
        """
        Return information about the current
        ChromaDB vector store.
        """

        return {
            "database":
                "ChromaDB",

            "collection":
                self.COLLECTION_NAME,

            "embedding_model":
                self.EMBEDDING_MODEL,

            "stored_chunks":
                self.collection.count(),

            "storage_path":
                str(self.vector_db_path)
        }


# -----------------------------------------------------
# SINGLETON VECTOR SERVICE INSTANCE
# -----------------------------------------------------

vector_service = VectorService()